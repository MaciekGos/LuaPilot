const fs = require("fs");
const vm = require("vm");
const path = require("path");
const win = { LP: {} };
win.window = win;
vm.createContext(win);
for (const f of ["core/config.js", "core/parser.js"]) vm.runInContext(fs.readFileSync(path.join(__dirname, "..", f), "utf8"), win);
const { analyze, isInjected, injectedKind } = win.LP.parser;
let bad = 0;
const t = (name, ok) => { console.log((ok ? "PASS " : "FAIL ") + name); if (!ok) bad++; };

let r = analyze('ok\n```\n@@LPCALL@@\n{"name":"inspect_instance","args":{"path":"Workspace"}}\n@@LPEND@@\n```');
t("basic call", r.kind === "call" && r.calls[0].name === "inspect_instance" && r.calls[0].args.path === "Workspace");
r = analyze("```\n@@LPLUA@@\nreturn 1\n@@LPEND@@\n```");
t("lua default Edit", r.kind === "call" && r.calls[0].args.datamodel_type === "Edit" && r.calls[0].args.code === "return 1");
r = analyze("@@LPLUA:Server@@\nreturn 2\n@@LPEND@@");
t("lua server", r.calls[0].args.datamodel_type === "Server");
r = analyze('@@LPCALL@@\n{"name":"script_read","args":{"target_file":"a\nb"}}\n@@LPEND@@');
t("raw newline in string", r.kind === "call" && r.calls[0].args.target_file === "a\nb");
r = analyze('@@LPCALL@@\n{"name":"x","args":{"a":1}\n@@LPEND@@');
t("missing closer salvaged", r.kind === "call" && r.calls[0].name === "x");
r = analyze('@@LPCALL@@\n{"name":"x","args":');
t("unclosed", r.kind === "error" && r.reason === "unclosed");
r = analyze("@@LPCALL@@\nnot json\n@@LPEND@@");
t("broken", r.kind === "error" && r.reason === "broken");
r = analyze("<｜DSML｜function_calls>");
t("dsml", r.kind === "error" && r.reason === "dsml");
r = analyze("@@LPCALL@@\n{\"name\":\"a\"}\n@@LPEND@@\n@@LPCALL@@\n{\"name\":\"b\"}\n@@LPEND@@");
t("many", r.kind === "many" && r.names.length === 2);
r = analyze("Use @@LPCALL@@ blocks to run things.");
t("prose mention ignored", r.kind === "none");
r = analyze('```json\n{"name":"get_studio_state","args":{}}\n```', ["get_studio_state"]);
t("bare json known", r.kind === "call");
r = analyze('```json\n{"name":"foo"}\n```', ["get_studio_state"]);
t("bare json unknown ignored", r.kind === "none");
t("injected", isInjected("⟦LP⟧ result · x\nfoo") && !isInjected("hello"));
t("kind", injectedKind("⟦LP⟧ ERROR · multi_edit\nx").kind === "error");
r = analyze('```\n@@LPCALL@@ {"name":"script_read","args":{"target_file":"a.b"}} @@LPEND@@\n```');
t("one-line call", r.kind === "call" && r.calls[0].name === "script_read");
r = analyze("```json\n@@LPCALL@@\n{\"name\":\"x\"}\n@@LPEND@@```");
t("fence glued to end marker", r.kind === "call");
r = analyze("Use @@LPLUA@@ blocks for code.");
t("lua prose ignored", r.kind === "none");
r = analyze('Done.\n<｜｜DSML｜｜ invoke name="search_game_tree">\n<｜｜DSML｜｜ parameter name="head_limit">80\n<｜｜DSML｜｜ parameter name="path">ServerStorage.TreePackB');
t("dsml read as a call", r.kind === "call" && r.calls[0].name === "search_game_tree" && r.calls[0].args.head_limit === "80" && r.calls[0].args.path === "ServerStorage.TreePackB" && r.calls[0].dsml === true);
process.exit(bad ? 1 : 0);
